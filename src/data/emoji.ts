export function firstGrapheme(value: string) {
  const clean = value.replace(/\s/g, '');
  if (!clean) return '';
  if (typeof Intl !== 'undefined' && 'Segmenter' in Intl) {
    const seg = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
    const first = seg.segment(clean)[Symbol.iterator]().next().value as { segment?: string } | undefined;
    return first?.segment ?? '';
  }
  return Array.from(clean)[0] ?? '';
}

export function isEmoji(value: string) {
  const glyph = firstGrapheme(value);
  if (!glyph) return false;
  try {
    if (/^[\p{L}\p{N}]+$/u.test(glyph)) return false;
    return /\p{Extended_Pictographic}/u.test(glyph) || /\p{Emoji}/u.test(glyph);
  } catch {
    if (/^[A-Za-z0-9А-Яа-яЁё]+$/.test(glyph)) return false;
    return /[^\u0000-\u007F]/.test(glyph);
  }
}

export function filterEmojiGroups(query: string): EmojiGroup[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_GROUPS;
  return EMOJI_GROUPS.map((group) => ({
    ...group,
    glyphs: group.label.toLowerCase().includes(q)
      ? group.glyphs
      : group.glyphs.filter((glyph) => glyph.includes(q)),
  })).filter((group) => group.glyphs.length);
}

export function episodeSource(ep: FreemanEpisode): PlayerSource | null {
  if (ep.youtubeId) return { type: 'youtube', id: ep.youtubeId };
  if (ep.vimeoId) return { type: 'vimeo', id: ep.vimeoId };
  return null;
}


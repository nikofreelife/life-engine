function hashDay(day: string) {
  let h = 2166136261;
  for (let i = 0; i < day.length; i += 1) {
    h ^= day.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function shiftDay(day: string, delta: number) {
  const date = new Date(`${day}T12:00:00`);
  date.setDate(date.getDate() + delta);
  return todayKey(date);
}

/** One quote per calendar day (YYYY-MM-DD). Next civil day → next quote. */
export function quoteForDay(day = todayKey()): DailyQuote & { day: string } {
  const n = DAILY_QUOTES.length;
  let idx = hashDay(day) % n;
  const yesterday = hashDay(shiftDay(day, -1)) % n;
  if (idx === yesterday) idx = (idx + 1) % n;
  const quote = DAILY_QUOTES[idx];
  return { ...quote, day };
}
